const fs = require("fs");

const PLUGIN_NAME = "ElmTypesRspackPlugin";

/**
 * Generates a `<file>.elm.d.ts` next to every compiled `.elm` module, using
 * lydell/elm-ts-types to type the module's `init`, flags, and ports.
 *
 * Reuses the already-compiled JS from elm-webpack-loader (via
 * `module.originalSource()`) instead of invoking `elm make` a second time,
 * since elm-ts-types needs the exact, unwrapped compiler output to `eval`.
 *
 * @example
 * new ElmTypesRspackPlugin()
 * new ElmTypesRspackPlugin({ test: /\.elm$/ })
 */
class ElmTypesRspackPlugin {
  /**
   * @param {object} [options]
   * @param {RegExp} [options.test] Matches module resource paths to generate
   *   types for. Defaults to any `.elm` file.
   */
  constructor({ test = /\.elm$/ } = {}) {
    this.test = test;
    this.generateTypeScriptPromise = import("elm-ts-types").then(
      ({ generateTypeScript }) => generateTypeScript,
    );
  }

  /** Writes `<resource>.d.ts` from the given compiled Elm JS. */
  generate(resource, compiledJs) {
    return this.generateTypeScriptPromise.then((generateTypeScript) => {
      const typeDefinition = `// Generated by ${PLUGIN_NAME}. Manual edits will be lost.
${generateTypeScript(compiledJs)}
export const Elm: typeof Elm;
`;
      fs.writeFileSync(`${resource}.d.ts`, typeDefinition);
    });
  }

  apply(compiler) {
    compiler.hooks.compilation.tap(PLUGIN_NAME, (compilation) => {
      // succeedModule is synchronous, so generation runs fire-and-forget per
      // module. Each attempt is tracked here and awaited in finishModules,
      // which delays sealing the compilation until generation has settled,
      // so any failure still lands in this build's compilation.errors.
      const pending = [];

      compilation.hooks.succeedModule.tap(PLUGIN_NAME, (module) => {
        const resource = module.resource;
        if (!resource || !this.test.test(resource)) {
          return;
        }

        const source = module.originalSource && module.originalSource();
        if (!source) {
          return;
        }

        pending.push(
          this.generate(resource, source.source().toString()).catch(
            (error) => {
              compilation.errors.push(
                new Error(`${PLUGIN_NAME} failed for ${resource}: ${error.message}`),
              );
            },
          ),
        );
      });

      compilation.hooks.finishModules.tapPromise(PLUGIN_NAME, () =>
        Promise.all(pending),
      );
    });
  }
}

module.exports = ElmTypesRspackPlugin;
